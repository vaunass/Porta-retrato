  function icon(name) { return P(ICONS[name] || ''); }
  function paintIcons(root) {
    var els = (root || document).querySelectorAll('i[data-ic]');
    for (var i = 0; i < els.length; i++) if (!els[i].firstChild) els[i].innerHTML = icon(els[i].getAttribute('data-ic'));
  }

  var store = {
    get: function (k, d) { try { var v = localStorage.getItem('iptv.' + k); return v === null ? d : JSON.parse(v); } catch (e) { return d; } },
    set: function (k, v) { try { localStorage.setItem('iptv.' + k, JSON.stringify(v)); } catch (e) { /* modo privado */ } }
  };

  function api(path, opts) {
    opts = opts || {};
    var init = { method: opts.method || 'GET', headers: {} };
    if (opts.body !== undefined) { init.method = opts.method || 'POST'; init.body = JSON.stringify(opts.body); init.headers['Content-Type'] = 'application/json'; }
    return fetch(path, init).then(function (r) {
      return r.json().then(function (j) { if (!r.ok) throw new Error(j.error || ('HTTP ' + r.status)); return j; });
    });
  }

  function esc(s) {
    return String(s == null ? '' : s).replace(/[&<>"']/g, function (c) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
    });
  }

  function $(id) { return document.getElementById(id); }

  var toastTimer = null;
  function toast(msg, ms) {
    var t = $('toast');
    t.textContent = msg; t.hidden = false;
    clearTimeout(toastTimer);
    toastTimer = setTimeout(function () { t.hidden = true; }, ms || 2600);
  }

  function debounce(fn, ms) {
    var t = null;
    return function () { var a = arguments, s = this; clearTimeout(t); t = setTimeout(function () { fn.apply(s, a); }, ms); };
  }

  function fmtTime(s) {
    if (!isFinite(s) || s < 0) s = 0;
    s = Math.floor(s);
    var h = Math.floor(s / 3600), m = Math.floor((s % 3600) / 60), x = s % 60;
    return (h ? h + ':' + (m < 10 ? '0' : '') : '') + m + ':' + (x < 10 ? '0' : '') + x;
  }

  function uid() { return 'd' + Math.random().toString(36).slice(2, 10) + Date.now().toString(36).slice(-4); }

  w.U = { icon: icon, paintIcons: paintIcons, store: store, api: api, esc: esc, $: $, toast: toast, debounce: debounce, fmtTime: fmtTime, uid: uid };
